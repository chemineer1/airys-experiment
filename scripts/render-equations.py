#!/usr/bin/env python3
"""Regenerate embedded LaTeX math assets; optional authoring tool, not a build step.

Requires matplotlib==3.10.8 (Mathtext + bundled STIX fonts). Ordinary Rust/browser
builds use committed alpha masks and do not need Python, TeX, or network access.
"""
import io
from pathlib import Path
import re
import struct

import matplotlib
from matplotlib.font_manager import FontProperties
from matplotlib.mathtext import math_to_image
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "assets" / "equations"
DEST.mkdir(parents=True, exist_ok=True)
matplotlib.rcParams["mathtext.fontset"] = "stix"
matplotlib.rcParams["savefig.transparent"] = True
equations = re.findall(r"\$\$\n(.*?)\n\$\$", (ROOT / "docs/EXPLANATION.md").read_text(), re.S)
assert equations, "No display equations found"
manifest = ["// Generated by scripts/render-equations.py. Do not edit.",
            "const EQUATIONS: &[(&str, &[u8])] = &["]
for i, latex in enumerate(equations):
    output = io.BytesIO()
    math_to_image(f"${latex}$", output, prop=FontProperties(size=24), dpi=216,
                  format="png", color="white")
    image = Image.open(output).convert("RGBA")
    # Header + one byte per pixel. Decode directly in egui, avoiding a runtime
    # image codec or a browser-only math engine. Three pixels per UI point.
    (DEST / f"{i}.alpha").write_bytes(struct.pack("<II", *image.size) + image.getchannel("A").tobytes())
    manifest.append(f'    (r###"{latex}"###, include_bytes!("{i}.alpha")),')
manifest.append("];")
(DEST / "manifest.rs").write_text("\n".join(manifest) + "\n")
print(f"Rendered {len(equations)} equations into {DEST}")
